#!/usr/bin/env python3
"""Round 127: THE BOSS-FIGHT OVERHAUL, proposals for the Lab (Kris: "a full rehaul of boss attacks and battles. they are too similar to each
other right now … most all bosses can teleport around, but bosses like skeletons shouldn't … a long list of all of the bosses, and around 10
proposals for what their attacks could be on top of their current attacks … thematic to the boss … at least 50 different types").
Writes lab/src/js/79y-0-bossplan-data.js (LBPLAN): the catalogue (boss_plan_types), every boss with its current attacks (from the Lab's own
boss list, LBB) and how it moves today, its proposed way to close the gap, and its 10 proposals; and the painted units bosses bring in.
    python tools/world/boss_plan.py"""
import json, os, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from boss_plan_types import TYPES, THEMES
from boss_plan_a import A
from boss_plan_b import B
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
T = {t[0]: t for t in TYPES}
NATURE = {'magic': 'magic — may blink', 'brute': 'brute — no teleport', 'beast': 'beast — no teleport', 'undead': 'undead — no teleport',
          'construct': 'construct — no teleport'}
bosses, bad = [], []
for key, name, where, nature, move, props in A + B:
    assert len(props) == 10, (key, len(props))
    for p in props:
        if p[0] not in T: bad.append((key, p[0]))
    if move[0] not in T: bad.append((key, move[0]))
    if nature != 'magic' and move[0] == 'blink': bad.append((key, 'non-magic blink'))
    bosses.append({'id': key, 'name': name, 'where': where, 'nature': nature, 'move': {'t': move[0], 'd': move[1]},
                   'p': [{'t': p[0], 'n': p[1], 'd': p[2], 'art': bool(p[3])} for p in props]})
assert not bad, bad
use = collections.Counter(p['t'] for b in bosses for p in b['p'])
units = json.load(open(os.path.join(R, 'lab', 'preview', 'bossplan', 'units.json')))
data = {'themes': {k: {'n': v[0], 'col': v[1]} for k, v in THEMES.items()},
        'types': [{'id': t[0], 'th': t[1], 'ic': t[2], 'n': t[3], 'd': t[4], 'from': t[5], 'uses': use.get(t[0], 0)} for t in TYPES],
        'bosses': bosses, 'units': units}
out = os.path.join(R, 'lab', 'src', 'js', '79y-0-bossplan-data.js')
open(out, 'w', encoding='utf-8').write('// generated by tools/world/boss_plan.py — round 127, the boss-fight overhaul (do not edit by hand)\nvar LBPLAN=' +
                                       json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('%d types, %d bosses, %d proposals (%d need new art), %d types used, %d units → %s' % (
    len(TYPES), len(bosses), sum(len(b['p']) for b in bosses), sum(p['art'] for b in bosses for p in b['p']), len(use), len(units), out))
