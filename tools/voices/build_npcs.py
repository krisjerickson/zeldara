"""Round 133: BACKSTORIES FOR EVERYONE ELSE (Kris's picks in Lab › Backstories for everyone else; depth: "at least 40 lines each, like the
villagers"). One Markdown file per group in src/npcs/ (the shared lore in src/npcs/_lore-<group>.md), built into
  src/js/21w4-0-npc-lines.js            ZNPC   — every line the game can say, by NPC (21w4-npc-talk.js speaks them)
  lab/src/js/79z8-0-npc-stories-data.js LNPC   — the stories, the lore and the line counts, for the Lab
File format (as src/villagers): '# Name', then key / who / group / realm / fairy (index) / kind / spirits, then
  ## Backstory   paragraphs           ## Before | ## After | ## Life | ## Stage 1 … ## Stage 5   one line each ('- ')
    Before: while the spirits she keeps are still bound. After: once they are free. Life: her own little life, any time.
    Stage N: only while the furthest realm open is N (5 = after the end).
python tools/voices/build_npcs.py     (prints each NPC's count against the 40; exit 1 on a repeated line or a god named before Stage 5)"""
import os, re, sys, json, glob
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(R, 'src', 'npcs')
GODS = re.compile(r"\b(Odin|Freya|Allfather|All-father|Thor|Frigg|Loki|Baldur|Heimdall|Tyr)\b")
TARGET = 40

def parse(txt):
    n = {'lines': {}}; sec = None
    for raw in txt.split('\n'):
        l = raw.rstrip()
        if l.startswith('# '): n['name'] = l[2:].strip(); continue
        if l.startswith('## '): sec = l[3:].strip().lower(); continue
        m = re.match(r'^(key|who|group|realm|fairy|kind|spirits|title):\s*(.*)$', l)
        if m and sec is None: n[m.group(1)] = m.group(2).strip(); continue
        if sec in ('backstory', 'scene'):
            key = 'story' if sec == 'backstory' else 'scene'
            if l.strip(): n[key] = (n.get(key, '') + ' ' + l.strip()).strip()
        elif sec and l.startswith('- '):
            n['lines'].setdefault(sec.replace(' ', ''), []).append(l[2:].strip())
    return n

def main():
    out, bad = {}, []
    for f in sorted(glob.glob(os.path.join(SRC, '*.md'))):
        if os.path.basename(f).startswith('_'): continue
        for part in re.split(r'\n(?=# )', open(f, encoding='utf-8').read()):
            if not part.strip().startswith('# '): continue
            n = parse(part); k = n.get('key')
            if not k: continue
            seen = set()
            for sec, L in n['lines'].items():
                for line in L:
                    if line in seen: bad.append('%s: repeated line: %s' % (k, line[:60]))
                    seen.add(line)
                    if sec != 'stage5' and GODS.search(line): bad.append('%s: a god named before the end (%s): %s' % (k, sec, line[:60]))
            out[k] = n
    lore = {}
    for f in glob.glob(os.path.join(SRC, '_lore-*.md')):
        lore[os.path.basename(f)[6:-3]] = open(f, encoding='utf-8').read()
    G = {}
    for k, n in out.items():
        cnt = sum(len(v) for v in n['lines'].values()); n['count'] = cnt; G.setdefault(n.get('group', '?'), []).append(k)
        print('  %-10s %-9s %3d / %d  %s' % (k, n.get('group', ''), cnt, TARGET, 'ok' if cnt >= TARGET else 'short'))
    game = {k: {'who': n.get('who', n.get('name')), 'group': n.get('group'), 'realm': int(n.get('realm', 0) or 0), 'fairy': int(n['fairy']) if n.get('fairy', '').isdigit() else None,
                'spirits': [s.strip() for s in n.get('spirits', '').split(',') if s.strip()], 'lines': n['lines']} for k, n in out.items()}
    for k, n in out.items():
        if n.get('scene'): game[k]['scene'] = 'pn_' + k
    sc = [{'id': 'sc_pn_' + k, 'wave': 133, 'fam': 'panels', 'kind': 'room', 'panel': True, 'cols': 1, 'rows': 1, 'size': '1536x1024',
           'title': 'Story panel — ' + n.get('who', k) + ', before the dark', 'items': [['pn_' + k, n.get('who', k) + ' — before the dark',
           'a wide cinematic painting in the game\'s painted Norse storybook style, warm and hopeful, set twenty-eight winters ago, before the gate shut: ' + n['scene'] + ' No text, no letters.', 1536, 1024]]}
          for k, n in sorted(out.items()) if n.get('scene')]
    open(os.path.join(R, 'src', 'js', '07zt25-art-r133-npc-scenes.js'), 'w', encoding='utf-8').write(
        '// generated by tools/voices/build_npcs.py from src/npcs/*.md (## Scene) — round 133: the mage-tower masters as they were, the scene after the fight\n'
        '// (Kris: "let\'s make sure to make the requests for the scenes for this option").   .\\tools\\sprites\\paint.ps1 -List r133_scenes\n'
        '(function(){ if(typeof ZSCN===\'undefined\')return; ZSCN.WAVES[133]=\'Round 133 — the mage-tower masters as they were (the scene after each fight)\';\n  ' +
        json.dumps(sc, ensure_ascii=False) + '.forEach(function(S){ ZSCN.SHEETS.push(S); });\n})();\n')
    open(os.path.join(R, 'sprites', 'requests', 'r133_scenes.txt'), 'w', encoding='utf-8').write(
        '# Round 133 — the mage-tower masters as they were, before the dark (one story panel each, shown after you beat them).\n#   .\\tools\\sprites\\paint.ps1 -List r133_scenes\n' + '\n'.join(S['id'] for S in sc) + '\n')
    open(os.path.join(R, 'src', 'js', '21w4-0-npc-lines.js'), 'w', encoding='utf-8').write(
        '// generated by tools/voices/build_npcs.py from src/npcs/*.md — round 133, the backstories for everyone else (do not edit by hand)\nvar ZNPC=' + json.dumps(game, ensure_ascii=False, separators=(',', ':')) + ';\n')
    lab = {'npcs': {k: {'who': n.get('who', n.get('name')), 'group': n.get('group'), 'realm': n.get('realm'), 'kind': n.get('kind', ''), 'spirits': n.get('spirits', ''), 'story': n.get('story', ''), 'lines': n['lines'], 'count': n['count']} for k, n in out.items()},
           'lore': lore, 'target': TARGET}
    open(os.path.join(R, 'lab', 'src', 'js', '79z8-0-npc-stories-data.js'), 'w', encoding='utf-8').write(
        '// generated by tools/voices/build_npcs.py — round 133 (do not edit by hand)\nvar LNPC=' + json.dumps(lab, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print('%d NPCs, %d lines' % (len(out), sum(n['count'] for n in out.values())))
    for b in bad: print('  ✗', b)
    sys.exit(1 if bad else 0)

if __name__ == '__main__': main()
